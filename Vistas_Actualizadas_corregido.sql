    S.SERVICIOS,
    CASE
        WHEN UPPER(M.TAGS) LIKE '%NO CRITICO%' THEN 'NO CRITICO'
        WHEN UPPER(M.TAGS) LIKE '%CRITICO%'    THEN 'CRITICO'
        ELSE 'SIN CRITICIDAD'
    END



--Detalle Infraestructura

CREATE OR REPLACE VIEW VW_DETALLE_INFRAESTRUCTURA AS
SELECT
    M.NOMBRE_VM,

    REGEXP_SUBSTR(M.IPV4, '^[^.]+\.[^.]+') AS SEGMENTO_IP,

    CASE
        WHEN UPPER(M.DISCOS) LIKE '%VSANDATASTORE%' THEN 'VSANDATASTORE'
        WHEN UPPER(M.DISCOS) LIKE '%UNKNOWN%' THEN 'UNKNOWN'
        WHEN UPPER(M.DISCOS) LIKE '%FS5K%' THEN 'FS5K'
        WHEN UPPER(M.DISCOS) LIKE '%FS7%' THEN 'FS7'
        WHEN UPPER(M.DISCOS) LIKE '%ASPECTDRP%' THEN 'ASPECTDRP'
        WHEN UPPER(M.DISCOS) LIKE '%DATASTORE3000%' THEN 'DATASTORE3000'
        WHEN UPPER(M.DISCOS) LIKE '%DATASTORE1%' THEN 'DATASTORE1'
        WHEN UPPER(M.DISCOS) LIKE '%DATASTORE_LOCAL%' THEN 'DATASTORE_LOCAL'
        ELSE 'OTROS'
    END AS DATASTORE,

    CASE
        WHEN UPPER(NVL(U.UBICACION,'N/A')) IN ( 'SAN PEDRO SULA')
            THEN 'SAN PEDRO SULA'
             WHEN UPPER(NVL(U.UBICACION,'N/A')) IN ('TEGUCIGALPA')
            THEN 'TEGUCIGALPA'
        WHEN UPPER(NVL(U.UBICACION,'N/A')) = 'BOGOTA'
            THEN 'BOGOTA'
        WHEN UPPER(NVL(U.UBICACION,'N/A')) = 'MIAMI'
            THEN 'MIAMI'
        WHEN UPPER(NVL(U.UBICACION,'N/A')) = 'N/A'
            THEN 'N/A'
        ELSE NVL(U.UBICACION,'N/A')
    END AS UBICACION

FROM ASHLY.MACHINE_MASTER_INV M
LEFT JOIN ASHLY.UBICACION_INV U
    ON M.ID_UBICACION = U.ID_UBICACION
WHERE UPPER(M.ESTADO) = 'ENCENDIDO';

