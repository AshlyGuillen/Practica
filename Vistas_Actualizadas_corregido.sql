

---RESUMEN SERVICIOS

  CREATE OR REPLACE FORCE NONEDITIONABLE VIEW "ASHLY"."VW_RESUMEN_SERVICIOS" ("SERVICIOS", "TOTAL_EQUIPOS", "TIPO_CRITICIDAD", "CRITICIDAD_PORCENTAJE") AS 
  SELECT
    SERVICIOS,
    SUM(TOTAL) AS TOTAL_EQUIPOS,
    CASE
        WHEN SUM(CASE WHEN TIPO = 'CRITICO'    THEN TOTAL ELSE 0 END) > 0 THEN 'CRITICO'
        WHEN SUM(CASE WHEN TIPO = 'NO CRITICO' THEN TOTAL ELSE 0 END) > 0 THEN 'NO CRITICO'
        ELSE 'SIN CRITICIDAD'
    END AS TIPO_CRITICIDAD,
    ROUND(SUM(CASE WHEN TIPO = 'CRITICO' THEN TOTAL ELSE 0 END) * 100 / SUM(TOTAL), 2)
        AS CRITICIDAD_PORCENTAJE
FROM "ASHLY"."VW_CRITICIDAD_SERVICIO"
GROUP BY SERVICIOS
ORDER BY TOTAL_EQUIPOS DESC, SERVICIOS
FETCH FIRST 50 ROWS ONLY


---TOP 50 SERVICIOS
CREATE OR REPLACE VIEW VW_TOP_50_SERVICIOS AS
SELECT *
FROM (
    SELECT
        S.SERVICIOS,
        COUNT(*) AS TOTAL_SERVIDORES,
        RANK() OVER (ORDER BY COUNT(*) DESC) AS POSICION
    FROM ASHLY.MACHINE_MASTER_INV M
    INNER JOIN ASHLY.SERVICIOS_INV S
        ON M.ID_SERVICIOS = S.ID_SERVICIOS
    WHERE UPPER(M.ESTADO) = 'ENCENDIDO'
    GROUP BY S.SERVICIOS
)
WHERE POSICION <= 20;


--CRITICIDAD POR SERVICIO

  CREATE OR REPLACE FORCE NONEDITIONABLE VIEW "ASHLY"."VW_CRITICIDAD_SERVICIO" ("SERVICIOS", "TIPO", "TOTAL") AS 
  SELECT
    S.SERVICIOS,
    CASE
        WHEN UPPER(M.TAGS) LIKE '%NO CRITICO%' THEN 'NO CRITICO'
        WHEN UPPER(M.TAGS) LIKE '%CRITICO%'    THEN 'CRITICO'
