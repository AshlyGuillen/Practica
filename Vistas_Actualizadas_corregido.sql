   CREATE OR REPLACE FORCE NONEDITIONABLE VIEW "ASHLY"."VW_ESX" ("ESX", "VERSION", "DATACENTER", "TOTAL_MAQUINAS") AS 
  SELECT
    M.ESX,
    V.VERSION,
    D.DATACENTER,
    SUM(
        CASE
            WHEN UPPER(M.ESTADO) = 'ENCENDIDO' THEN 1
            ELSE 0
        END
    ) AS TOTAL_MAQUINAS
FROM MACHINE_MASTER_INV M
INNER JOIN CLUSTER_INV C
    ON M.ID_CLUSTER_VM = C.ID_CLUSTER_VM
INNER JOIN DATACENTER_INV D
    ON C.ID_DATACENTER_INV = D.ID_DATACENTER_INV
LEFT JOIN (
    SELECT 'esxiqa' ESX, 'V.4.0' VERSION FROM DUAL
      UNION ALL SELECT 'esxidev', 'V.4.0' FROM DUAL
    UNION ALL SELECT 'hnbnesxhci', 'V.4.0' FROM DUAL
    UNION ALL SELECT 'hnbnesxhcisps', 'V.4.0' FROM DUAL
    UNION ALL SELECT 'aspectdrp', '7.0.3' FROM DUAL
    

) V
    ON UPPER(M.ESX) = UPPER(V.ESX)
WHERE M.ESX IS NOT NULL
GROUP BY
    M.ESX,
    V.VERSION,
    D.DATACENTER
ORDER BY
    D.DATACENTER,
    M.ESX

  
