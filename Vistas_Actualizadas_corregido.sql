---RESUMEN AGENTES
CREATE OR REPLACE VIEW VW_RESUMEN_AGENTES_INSTALADOS AS
SELECT

    SUM(
        CASE
            WHEN NVL(UPPER(M.TREND),'N/A') IN ('N/A','NO')
             AND NVL(UPPER(M.CORTEX),'N/A') IN ('N/A','NO')
             AND NVL(UPPER(M.TRELLIX),'N/A') IN ('N/A','NO')
            THEN 1
            ELSE 0
        END
    ) AS ANTIVIRUS_NO_APLICA,

    SUM(
        CASE
            WHEN UPPER(M.TREND) = 'SI'
              OR UPPER(M.CORTEX) = 'SI'
              OR UPPER(M.TRELLIX) = 'SI'
            THEN 1
            ELSE 0
        END
    ) AS ANTIVIRUS_INSTALADO,
    
    
--lumu
    /* DEV + QA */

SUM(
    CASE
        WHEN UPPER(A.AMBIENTE) IN ('DEV','QA','PRD')
         AND UPPER(M.LUMU) = 'SI'
        THEN 1 ELSE 0
    END
) AS LUMU_INSTALADO,

SUM(
    CASE
        WHEN UPPER(A.AMBIENTE) IN ('DEV','QA','PRD')
         AND UPPER(M.LUMU) = 'NO'
        THEN 1 ELSE 0
    END
) AS LUMU_NO_INSTALADO,

SUM(
    CASE
        WHEN UPPER(A.AMBIENTE) IN ('DEV','QA','PRD')
         AND NVL(UPPER(M.LUMU),'N/A') = 'N/A'
        THEN 1 ELSE 0
    END
) AS LUMU_NO_APLICA,





    /* SENTINEL */
   /* DEV + QA */

SUM(
    CASE
        WHEN UPPER(A.AMBIENTE) IN ('DEV','QA','PRD')
         AND UPPER(M.SENTINEL) = 'SI'
        THEN 1 ELSE 0
    END
) AS SENTINEL_INSTALADO,

SUM(
    CASE
        WHEN UPPER(A.AMBIENTE) IN ('DEV','QA','PRD')
         AND UPPER(M.SENTINEL) = 'NO'
        THEN 1 ELSE 0
    END
) AS SENTINEL_NO_INSTALADO,

SUM(
    CASE
        WHEN UPPER(A.AMBIENTE) IN ('DEV','QA','PRD')
         AND NVL(UPPER(M.SENTINEL),'N/A') = 'N/A'
        THEN 1 ELSE 0
    END
) AS SENTINEL_NO_APLICA,








    /* TENABLE */
    SUM(CASE WHEN UPPER(M.TENABLE) = 'SI' THEN 1 ELSE 0 END) AS TENABLE_INSTALADO,
    SUM(CASE WHEN UPPER(M.TENABLE) = 'NO' THEN 1 ELSE 0 END) AS TENABLE_NO_INSTALADO,
    SUM(CASE WHEN NVL(UPPER(M.TENABLE),'N/A') = 'N/A' THEN 1 ELSE 0 END) AS TENABLE_NO_APLICA,

    /* ENDPOINT CENTRAL */
    SUM(CASE WHEN UPPER(M.ENDPOINT_CENTRAL) = 'SI' THEN 1 ELSE 0 END) AS ENDPOINT_CENTRAL_INSTALADO,
    SUM(CASE WHEN UPPER(M.ENDPOINT_CENTRAL) = 'NO' THEN 1 ELSE 0 END) AS ENDPOINT_CENTRAL_NO_INSTALADO,
    SUM(CASE WHEN NVL(UPPER(M.ENDPOINT_CENTRAL),'N/A') = 'N/A' THEN 1 ELSE 0 END) AS ENDPOINT_CENTRAL_NO_APLICA,

    
 SUM(
    CASE
        WHEN UPPER(A.AMBIENTE) = 'PRD'
        THEN 1
        ELSE 0
    END
) AS TOTAL_PRD_ENCENDIDAS,

   SUM(
    CASE
        WHEN UPPER(A.AMBIENTE) IN ('DEV','QA')
        THEN 1
        ELSE 0
    END
) AS TOTAL_DEVQA_ENCENDIDAS

FROM ASHLY.MACHINE_MASTER_INV M
INNER JOIN ASHLY.AMBIENTE_INV A
    ON M.ID_AMBIENTE_inv = A.ID_AMBIENTE_INV
WHERE UPPER(M.ESTADO) = 'ENCENDIDO';

